CREATE TABLE categorias (
    id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 6) PRIMARY KEY,
    nombre VARCHAR2(100 CHAR) NOT NULL UNIQUE,
    descripcion VARCHAR2(500 CHAR) NOT NULL
);
CREATE TABLE temas (
    id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 4) PRIMARY KEY,
    titulo VARCHAR2(200 CHAR) NOT NULL,
    contenido VARCHAR2(4000 CHAR) NOT NULL,
    autor_id NUMBER(19) NOT NULL,
    categoria_id NUMBER(19) NOT NULL REFERENCES categorias(id)
);
CREATE TABLE comentarios (
    id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 4) PRIMARY KEY,
    contenido VARCHAR2(2000 CHAR) NOT NULL,
    autor_id NUMBER(19) NOT NULL,
    tema_id NUMBER(19) NOT NULL REFERENCES temas(id)
);
